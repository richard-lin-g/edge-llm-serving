def main():
    path = "results/d7_scores.csv"
    rows = list(csv.DictReader(open(path, encoding="utf-8")))
    missing = []
    for r in rows:
        k = (r["qid"], r["label"])
        if k not in SCORES:
            missing.append(k)
            continue
        f, fm, u, note = SCORES[k]
        r["fact"], r["format"], r["useful"], r["note"] = f, fm, u, note
    if missing:
        raise SystemExit(f"这些行没打上分：{missing}")
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["qid", "label", "fact", "format", "useful", "note"])
        w.writeheader()
        w.writerows(rows)
    print(f"已填 {len(rows)} 行 → {path}")

if __name__ == "__main__":
    main()
